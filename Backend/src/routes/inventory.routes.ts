import { Router } from "express";
import * as controller from "../controllers/inventory.controller.js";
const router = Router();
router.post("/products", controller.postproducts);
router.patch("/products/:id", controller.patchproductsId);
router.delete("/products/:id", controller.deleteproductsId);
router.post("/variants", controller.postvariants);
router.post("/inventory/:id/receive", controller.postInventoryReceive);
router.post("/inventory/:id/withdraw", controller.postInventoryWithdraw);
router.post("/inventory/:id/adjust", controller.postInventoryAdjust);
router.put("/products/:id/sizes", controller.putProductSizes);
router.get("/ca/:number", controller.getCaRegistry);
router.get("/categories", controller.getcategories);
export default router;
